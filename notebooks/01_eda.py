import pandas as pd
import kagglehub
import os
import shutil

# 1. Tải dataset từ Kaggle về (Sẽ trả về đường dẫn thư mục chứa file)
downloaded_path = kagglehub.dataset_download("fedesoriano/stroke-prediction-dataset")
print("Thư mục vừa tải về:", downloaded_path)

# 2. Tạo thư mục đích mong muốn
target_dir = './data/raw'
os.makedirs(target_dir, exist_ok=True)

# 3. Lấy tên file csv trong thư mục vừa tải và di chuyển vào thư mục đích
filename = 'healthcare-dataset-stroke-data.csv'
source_file = os.path.join(downloaded_path, filename)
target_file = os.path.join(target_dir, filename)

# Thực hiện di chuyển file
shutil.copy(source_file, target_file)
print(f"Đã di chuyển file vào đúng vị trí: {target_file}")

"""**2. Đọc tập dữ liệu và khám phá dữ liệu**"""

df = pd.read_csv("./data/raw/healthcare-dataset-stroke-data.csv")

print(df.head())

"""Kích thước của tập dữ liệu"""

print(df.shape)

"""Cấu trúc của tập dữ liệu"""

print(df.info())

"""=> Thấy được kiểu dữ liệu các cột và cột nào có các cột dữ liệu còn thiếu"""

print(df.describe())

print(df['stroke'].value_counts())

