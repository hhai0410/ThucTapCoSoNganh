import pandas as pd

df = pd.read_csv("./data/raw/healthcare-dataset-stroke-data.csv")

print(df.head())

"""# Trực quan hóa, làm sạch và tiền xử lý dữ liệu

"""

import seaborn as sns
import matplotlib.pyplot as plt

numerical_features = ['age', 'avg_glucose_level', 'bmi']

plt.figure(figsize=(15,12))

for i,feature in enumerate(numerical_features):
  # Vẽ biểu đồ hist bên trái, xong sau đó vẽ biểu đồ boxplot bên phải
  plt.subplot(len(numerical_features), 2, 2 * i + 1)
  sns.histplot(df[feature], kde=True, color='blue')
  plt.title(f'Phân bố của {feature}')
  plt.ylabel('Số lượng')
  plt.xlabel(f'{feature}')


  plt.subplot(len(numerical_features), 2, 2 * i + 2)
  sns.boxplot(x=df[feature], color='green')
  plt.title(f'Boxplot của {feature} (Tìm outliers)')
  plt.xlabel(feature)

plt.tight_layout()

plt.show()

categorical_features = ['gender', 'hypertension', 'heart_disease', 'ever_married',
                        'work_type', 'Residence_type', 'smoking_status', 'stroke']

plt.figure(figsize=(15, 18))

for i, feature in enumerate(categorical_features):
    # Khai báo vị trí ô: 4 hàng, 2 cột, vị trí thứ i+1
    plt.subplot(4, 2, i + 1)

    # Vẽ countplot đếm số lượng, dùng bảng màu Set2 cho đẹp
    sns.countplot(data=df, x=feature, palette='Set2')

    plt.title(f'Thống kê số lượng của {feature}', fontsize=12)
    plt.xlabel(feature)
    plt.ylabel('Số lượng')

    # Đối với các cột có tên hạng mục dài, xoay chữ 45 độ để không bị đè lên nhau
    if feature in ['work_type', 'smoking_status']:
        plt.xticks(rotation=45)

plt.tight_layout()
plt.show()

"""Quan tâm nhất vào cột stroke, nó bị mất cân bằng dữ liệu"""

